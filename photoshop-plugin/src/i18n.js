let CURRENT_LANG = 'fr';

function tr(key) {
  const table = TRANSLATIONS[CURRENT_LANG] || TRANSLATIONS.fr;
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  return key;
}

function setLang(lang) {
  if (lang === 'fr' || lang === 'en') CURRENT_LANG = lang;
  return CURRENT_LANG;
}

function getLang() {
  return CURRENT_LANG;
}

// Explicit preference wins; otherwise derive from the UXP host locale.
function initLang(prefLang, uxpLocale) {
  if (prefLang === 'fr' || prefLang === 'en') {
    CURRENT_LANG = prefLang;
  } else if (typeof uxpLocale === 'string' && uxpLocale.toLowerCase().indexOf('fr') === 0) {
    CURRENT_LANG = 'fr';
  } else {
    CURRENT_LANG = 'en';
  }
  return CURRENT_LANG;
}

module.exports = { tr, setLang, getLang, initLang, TRANSLATIONS };
